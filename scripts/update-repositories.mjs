import { writeFile, readFile } from 'node:fs/promises';
import { pathToFileURL } from 'node:url';

export function normalizeRepositories(repos) {
  if (!Array.isArray(repos) || repos.length > 1000) throw new Error('Invalid repository list');
  return repos.map(repo => {
    if (!repo || repo.private !== false || typeof repo.name !== 'string' || !/^[A-Za-z0-9_.-]{1,100}$/.test(repo.name) ||
        ['.', '..'].includes(repo.name) || !Number.isSafeInteger(repo.stargazers_count) ||
        repo.stargazers_count < 0 || repo.stargazers_count > 1e9) throw new Error('Invalid public repository');
    const text = (value, max) => typeof value === 'string' ? value.slice(0, max) : '';
    return { name: repo.name, stargazers_count: repo.stargazers_count,
      description: text(repo.description, 1000), language: text(repo.language, 80),
      topics: Array.isArray(repo.topics) ? repo.topics.filter(t => typeof t === 'string').slice(0, 4).map(t => t.slice(0, 80)) : [],
      updated_at: text(repo.updated_at, 40) };
  });
}

export async function fetchRepositories(fetcher = fetch, token = process.env.GITHUB_TOKEN) {
  const repos = [];
  for (let page = 1; page <= 10; page++) {
    const response = await fetcher(`https://api.github.com/users/Daugavan/repos?per_page=100&type=owner&sort=full_name&page=${page}`, {
      headers: { Accept: 'application/vnd.github+json', ...(token ? { Authorization: `Bearer ${token}` } : {}) },
      redirect: 'error', signal: AbortSignal.timeout(15000)
    });
    if (!response.ok) throw new Error(`GitHub repositories HTTP ${response.status}; keeping previous statistics`);
    const body = await response.text();
    if (Buffer.byteLength(body) > 2 * 1024 * 1024) throw new Error('Oversized repository response');
    const data = JSON.parse(body);
    if (!Array.isArray(data) || data.length > 100) throw new Error('Invalid repository page');
    repos.push(...normalizeRepositories(data));
    // Never follow arbitrary URLs supplied in Link headers.
    if (!/rel="next"/.test(response.headers.get('link') || '')) {
      if (new Set(repos.map(repo => repo.name)).size !== repos.length) throw new Error('Duplicate repositories');
      return { version: 1, retrieved: new Date().toISOString(), repos };
    }
  }
  throw new Error('Repository pagination limit reached; keeping previous statistics');
}

export function statisticsScript(repositories, activity) {
  if (repositories?.version !== 1 || activity?.version !== 1 || !activity.github || !activity.lovable) {
    throw new Error('Missing verified statistics');
  }
  return '// Public snapshots only. Generated by the scheduled statistics publisher.\n' +
    'window.portfolioStatistics = ' + JSON.stringify({ repositories, activity }).replaceAll('<', '\\u003c') + ';\n';
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const repositories = await fetchRepositories();
  const activity = JSON.parse(await readFile(new URL('../activity-snapshot.json', import.meta.url), 'utf8'));
  const script = statisticsScript(repositories, activity);
  await writeFile(new URL('../repositories-snapshot.json', import.meta.url), JSON.stringify(repositories) + '\n');
  await writeFile(new URL('../statistics-data.js', import.meta.url), script);
  console.log(`Verified ${repositories.repos.length} public repositories. No private data published.`);
}
